"""The feature registry and its causality contract (§7.1).

Every feature is registered with four pieces of metadata that the rest of the
system depends on:

* `inputs` — which bar columns it reads. Checked against a forbidden set at
  registration, so a spec whose computation graph touches the label cannot
  exist (§4, I5). This is enforcement by construction: there is no path through
  the API that produces a leaking feature and then relies on someone noticing.
* `lookback` — bars of warm-up, as a function of the parameters. The pipeline
  drops `max(lookback)` rows rather than filling them, so this number is the
  difference between an honest sample and a hundred back-filled observations
  an estimator will happily fit to.
* `family` — for the clustered importance report and the data dictionary.
* `description` — goes straight into `docs/data-dictionary.md`, generated by
  `python -m alphacore.features.registry --emit-docs`.

Run that command after adding a feature; CI checks the file regenerates
identically, so the documentation cannot drift from the code.
"""

from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import TYPE_CHECKING, Any, Final, Literal

from alphacore.errors import FeatureError, LeakageError

if TYPE_CHECKING:
    from collections.abc import Callable, Mapping

    import pandas as pd

__all__ = [
    "ALLOWED_INPUTS",
    "FAMILIES",
    "FORBIDDEN_INPUTS",
    "FeatureDefinition",
    "FeatureSpec",
    "emit_data_dictionary",
    "get",
    "register",
    "registered_names",
    "resolve",
]

Family = Literal[
    "trend", "momentum", "volatility", "volume", "returns", "statistical", "microstructure"
]

FAMILIES: Final[tuple[str, ...]] = (
    "trend",
    "momentum",
    "volatility",
    "volume",
    "returns",
    "statistical",
    "microstructure",
)

ALLOWED_INPUTS: Final[frozenset[str]] = frozenset(
    {"open", "high", "low", "close", "volume", "adj_factor"}
)
"""The only columns a feature may read. Anything else is either a label, a
derived target, or a column that does not exist at time `t`."""

FORBIDDEN_INPUTS: Final[frozenset[str]] = frozenset(
    {
        "label",
        "labels",
        "t_start",
        "t_end",
        "t_touch",
        "weight",
        "sample_weight",
        "realised_return",
        "forward_return",
        "target",
        "y",
    }
)
"""Columns that describe the future. Naming one as a feature input is a leak,
and the registry refuses to record it (§4, I5)."""

ComputeFn = "Callable[[pd.DataFrame, dict[str, Any]], pd.DataFrame]"
LookbackFn = "Callable[[dict[str, Any]], int]"


@dataclass(frozen=True)
class FeatureDefinition:
    """A registered feature template, before its parameters are known.

    Attributes:
        name: Registry key, e.g. `'rsi'`.
        fn: `fn(bars, params) -> DataFrame` of one or more named output columns.
        lookback_fn: Maps concrete parameters to bars of warm-up required.
        inputs: Bar columns read.
        family: Grouping used by the importance report and the data dictionary.
        description: One line, copied into the data dictionary.
        param_names: Accepted parameter names, used to reject typos.
        defaults: Default parameter values.
    """

    name: str
    fn: Callable[[pd.DataFrame, dict[str, Any]], pd.DataFrame]
    lookback_fn: Callable[[dict[str, Any]], int]
    inputs: frozenset[str]
    family: Family
    description: str
    param_names: frozenset[str]
    defaults: Mapping[str, Any]
    injects: frozenset[str] = frozenset()


@dataclass(frozen=True)
class FeatureSpec:
    """A feature with concrete parameters, ready to compute (§7.1).

    Attributes:
        name: Registry key.
        fn: The compute function.
        params: Concrete parameters, with defaults filled in.
        lookback: Bars of warm-up this parameterisation requires.
        inputs: Bar columns read. Never intersects `FORBIDDEN_INPUTS`.
        family: Grouping.
        description: One line, copied into the data dictionary.
        runtime: Values supplied by the pipeline rather than the user, such as
            `periods_per_year`. Passed to `fn` but deliberately excluded from
            `params`, so they never appear in a column name — the annualisation
            factor is a property of the dataset, not of the feature.
    """

    name: str
    fn: Callable[[pd.DataFrame, dict[str, Any]], pd.DataFrame]
    params: dict[str, Any]
    lookback: int
    inputs: frozenset[str]
    family: Family
    description: str
    runtime: dict[str, Any] = field(default_factory=dict)

    @property
    def call_params(self) -> dict[str, Any]:
        """Everything the compute function is called with."""
        return {**self.params, **self.runtime}


_REGISTRY: dict[str, FeatureDefinition] = {}


def register(
    *,
    name: str,
    family: Family,
    description: str,
    inputs: frozenset[str],
    lookback: Callable[[dict[str, Any]], int],
    defaults: Mapping[str, Any] | None = None,
    injects: frozenset[str] = frozenset(),
) -> Callable[
    [Callable[[pd.DataFrame, dict[str, Any]], pd.DataFrame]],
    Callable[[pd.DataFrame, dict[str, Any]], pd.DataFrame],
]:
    """Register a feature, rejecting anything that could see the future.

    Args:
        name: Registry key.
        family: Grouping.
        description: One line for the data dictionary.
        inputs: Bar columns the feature reads.
        lookback: Maps parameters to bars of warm-up.
        defaults: Default parameter values. The keys also define the accepted
            parameter names, so a typo is an error rather than a silent default.
        injects: Values the pipeline supplies rather than the user, such as
            `periods_per_year`. Excluded from column names and from the
            manifest's parameter record.

    Returns:
        A decorator that records the compute function and returns it unchanged.

    Raises:
        LeakageError: If `inputs` names a label or target column (§4, I5).
        FeatureError: If the name is taken, the family is unknown, the
            description is empty, or an input is not a bar column.
    """

    def decorator(
        fn: Callable[[pd.DataFrame, dict[str, Any]], pd.DataFrame],
    ) -> Callable[[pd.DataFrame, dict[str, Any]], pd.DataFrame]:
        forbidden = inputs & FORBIDDEN_INPUTS
        if forbidden:
            msg = (
                f"Feature {name!r} declares label column(s) {sorted(forbidden)} as inputs. "
                "A feature whose computation graph touches the label is a leak by "
                "construction (§4, I5) and cannot be registered."
            )
            raise LeakageError(msg)
        if name in _REGISTRY:
            msg = f"Feature {name!r} is already registered."
            raise FeatureError(msg)
        if family not in FAMILIES:
            msg = f"Feature {name!r} has unknown family {family!r}. Known: {list(FAMILIES)}."
            raise FeatureError(msg)
        if not description.strip():
            msg = f"Feature {name!r} needs a description; it becomes the data dictionary entry."
            raise FeatureError(msg)
        unknown_inputs = inputs - ALLOWED_INPUTS
        if unknown_inputs:
            msg = (
                f"Feature {name!r} reads {sorted(unknown_inputs)}, which are not bar columns. "
                f"Allowed: {sorted(ALLOWED_INPUTS)}."
            )
            raise FeatureError(msg)

        params = dict(defaults or {})
        _REGISTRY[name] = FeatureDefinition(
            name=name,
            fn=fn,
            lookback_fn=lookback,
            inputs=inputs,
            family=family,
            description=description.strip(),
            param_names=frozenset(params),
            defaults=params,
            injects=injects,
        )
        return fn

    return decorator


def registered_names() -> tuple[str, ...]:
    """List registered feature names.

    Returns:
        Names, sorted. Sorted rather than insertion-ordered so import order can
        never reach a column name or a documentation file (§4, I8).
    """
    return tuple(sorted(_REGISTRY))


def get(name: str) -> FeatureDefinition:
    """Look up a feature definition.

    Args:
        name: Registry key.

    Returns:
        The definition.

    Raises:
        FeatureError: If the name is not registered.
    """
    try:
        return _REGISTRY[name]
    except KeyError as exc:
        msg = f"Unknown feature {name!r}. Registered: {list(registered_names())}."
        raise FeatureError(msg) from exc


def resolve(
    name: str,
    params: Mapping[str, Any],
    *,
    context: Mapping[str, Any] | None = None,
) -> FeatureSpec:
    """Bind concrete parameters to a registered feature.

    Args:
        name: Registry key.
        params: Concrete parameter values. Missing ones take their defaults.
        context: Pipeline-supplied values for this feature's `injects`, such as
            `periods_per_year`.

    Returns:
        A frozen `FeatureSpec` with an integer lookback.

    Raises:
        FeatureError: If the feature is unknown, a parameter is not accepted,
            a required injected value is missing, or the parameters produce an
            invalid lookback.
    """
    definition = get(name)
    unexpected = set(params) - set(definition.param_names)
    if unexpected:
        msg = (
            f"Feature {name!r} got unexpected parameter(s) {sorted(unexpected)}. "
            f"Accepted: {sorted(definition.param_names)}."
        )
        raise FeatureError(msg)

    available = dict(context or {})
    missing = definition.injects - set(available)
    if missing:
        msg = (
            f"Feature {name!r} needs {sorted(missing)} from the pipeline context. "
            "This is supplied by build_features from the dataset's interval and calendar."
        )
        raise FeatureError(msg)

    resolved = {**definition.defaults, **params}
    lookback = definition.lookback_fn(resolved)
    if not isinstance(lookback, int | float) or lookback < 0:
        msg = f"Feature {name!r} produced an invalid lookback {lookback!r} for params {resolved}."
        raise FeatureError(msg)

    return FeatureSpec(
        name=definition.name,
        fn=definition.fn,
        params=resolved,
        lookback=int(lookback),
        inputs=definition.inputs,
        family=definition.family,
        description=definition.description,
        runtime={key: available[key] for key in sorted(definition.injects)},
    )


def emit_data_dictionary() -> str:
    """Render `docs/data-dictionary.md` from the registry.

    Returns:
        Markdown, deterministic given the registry contents.
    """
    lines = [
        "# Data dictionary",
        "",
        "Generated from the feature registry. Do not edit by hand:",
        "",
        "```bash",
        "just docs",
        "```",
        "",
        "`lookback` is bars of warm-up required, as a function of the feature's",
        "parameters. The pipeline drops `max(lookback)` rows rather than filling",
        "them (§7.1), so this column is the cost in sample size of using a feature.",
        "",
        "`inputs` lists every bar column the feature reads. No feature may read a",
        "label column; the registry rejects one that tries (§4, I5).",
        "",
    ]
    for family in FAMILIES:
        names = [n for n in registered_names() if _REGISTRY[n].family == family]
        if not names:
            continue
        lines += [
            f"## {family.capitalize()}",
            "",
            "| feature | inputs | parameters | description |",
            "|---|---|---|---|",
        ]
        for name in names:
            definition = _REGISTRY[name]
            params = (
                ", ".join(f"`{k}={v!r}`" for k, v in sorted(definition.defaults.items())) or "—"
            )
            inputs = ", ".join(f"`{c}`" for c in sorted(definition.inputs))
            lines.append(f"| `{name}` | {inputs} | {params} | {definition.description} |")
        lines.append("")
    return "\n".join(lines)


def _main() -> int:
    """Command-line entry point for regenerating the data dictionary.

    Returns:
        Process exit code.
    """
    parser = argparse.ArgumentParser(description="Feature registry utilities.")
    parser.add_argument(
        "--emit-docs", action="store_true", help="Emit the data dictionary as markdown."
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=None,
        help=(
            "Write to this path instead of stdout. Preferred on Windows, where "
            "shell redirection defaults to UTF-16 and would corrupt the file."
        ),
    )
    args = parser.parse_args()
    if not args.emit_docs:
        parser.print_help()
        return 1

    markdown = emit_data_dictionary()
    if args.output is None:
        sys.stdout.write(markdown)
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_bytes(markdown.encode("utf-8"))
    return 0


